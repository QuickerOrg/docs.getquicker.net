#!/usr/bin/env node
/**
 * Generate C# reference stub file data/script-action/qk-api.stub.cs
 * from data/script-action/catalog.json for AI coding context and verification.
 *
 * Usage:
 *   node tools/script-docs/gen-stub.mjs
 *   node tools/script-docs/gen-stub.mjs --check
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import {fileURLToPath} from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..', '..');
const catalogPath = path.join(repoRoot, 'data', 'script-action', 'catalog.json');
const outPath = path.join(repoRoot, 'data', 'script-action', 'qk-api.stub.cs');

const escXml = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\r?\n/g, ' ');

export function buildStubSource(catalog) {
  const lines = [
    '// <auto-generated>',
    `// Source: data/script-action/catalog.json (apiVersion=${catalog.apiVersion ?? 1}, productVersion=${catalog.productVersion ?? 'unknown'})`,
    `// Domains: ${(catalog.domains ?? []).length}, Types: ${(catalog.types ?? []).length}`,
    '// Do not edit manually; regenerate via `npm run docs:script:stub`.',
    '// </auto-generated>',
    '#nullable enable',
    'using System;',
    'using System.Collections.Generic;',
    'using System.Threading.Tasks;',
    '',
    'namespace Quicker.ScriptActions.Stubs',
    '{',
  ];

  lines.push('    public static partial class qk', '    {');
  for (const domain of catalog.domains ?? []) {
    const isRoot = domain.name === 'qk';
    const indent = isRoot ? '        ' : '            ';
    if (!isRoot) {
      if (domain.description) {
        lines.push(`        /// <summary>${escXml(domain.description)}</summary>`);
      }
      lines.push(`        public static class ${domain.name}`, '        {');
    }
    for (const m of domain.methods ?? []) {
      if (m.description) {
        lines.push(`${indent}/// <summary>${escXml(m.description)}</summary>`);
      }
      const sig = String(m.signature ?? '').trim();
      if (sig) {
        lines.push(`${indent}public static extern ${sig};`);
      }
    }
    if (!isRoot) lines.push('        }', '');
  }
  lines.push('    }', '');

  for (const t of catalog.types ?? []) {
    if (t.description) {
      lines.push(`    /// <summary>${escXml(t.description)}</summary>`);
    }
    lines.push(`    public partial class ${t.name}`, '    {');
    for (const c of t.constructors ?? []) {
      const sig = typeof c === 'string' ? c : c.signature;
      if (c?.description) lines.push(`        /// <summary>${escXml(c.description)}</summary>`);
      if (sig) lines.push(`        public extern ${sig.trim()};`);
    }
    for (const p of t.properties ?? []) {
      if (p.description) lines.push(`        /// <summary>${escXml(p.description)}</summary>`);
      const acc = p.writable ? '{ get; set; }' : '{ get; }';
      lines.push(`        public ${p.type} ${p.name} ${acc}`);
    }
    for (const m of t.methods ?? []) {
      if (m.description) lines.push(`        /// <summary>${escXml(m.description)}</summary>`);
      const sig = String(m.signature ?? '').trim();
      if (sig) lines.push(`        public extern ${sig};`);
    }
    lines.push('    }', '');
  }

  lines.push('}', '');
  return lines.join('\n');
}

if (
  process.argv[1] &&
  fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))
) {
  const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8').replace(/^\uFEFF/, ''));
  const expected = buildStubSource(catalog);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(outPath)) {
      console.error('缺少 data/script-action/qk-api.stub.cs，请运行 npm run docs:script:stub。');
      process.exit(1);
    }
    const actual = fs.readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n');
    if (actual !== expected) {
      console.error('data/script-action/qk-api.stub.cs 与 catalog.json 不一致，请运行 npm run docs:script:stub。');
      process.exit(1);
    }
    console.log(
      `qk-api.stub.cs 校验通过：${(catalog.domains ?? []).length} 个域，${(catalog.types ?? []).length} 个类型。`,
    );
  } else {
    fs.writeFileSync(outPath, expected, 'utf8');
    console.log(
      `已生成 data/script-action/qk-api.stub.cs：${(catalog.domains ?? []).length} 个域，${(catalog.types ?? []).length} 个类型。`,
    );
  }
}
